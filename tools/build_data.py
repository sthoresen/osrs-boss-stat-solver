#!/usr/bin/env python3
"""Build js/items.js and img/items/ from the OSRS wiki DPS calculator data.

Usage: python3 tools/build_data.py /path/to/osrs-dps-calc

Setups live in data/setups.json (hand-edited, loaded by the page at runtime).
This script only extracts the stats and icons of the items those setups use, the spell
max hits, and a few real bosses as presets, from https://github.com/weirdgloop/osrs-dps-calc.
Re-run it after adding an item that no setup used before.
"""
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CALC = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / 'osrs-dps-calc'

equipment = json.load(open(CALC / 'cdn/json/equipment.json'))
spells = json.load(open(CALC / 'cdn/json/spells.json'))
monsters = json.load(open(CALC / 'cdn/json/monsters.json'))
cfg = json.load(open(ROOT / 'data/setups.json'))

IMG_DIR = ROOT / 'img/items'
IMG_DIR.mkdir(parents=True, exist_ok=True)

items = {}


def slug(s):
    return re.sub(r'[^a-z0-9]+', '-', s.lower()).strip('-')


def add_item(spec):
    if spec in items:
        return
    name, _, version = spec.partition('|')
    hits = [e for e in equipment if e['name'] == name and (not version or e['version'] == version)]
    if not hits:
        raise SystemExit(f'missing item: {spec}')
    e = hits[0]
    img = slug(e['image'].rsplit('.', 1)[0]) + '.png'
    src = CALC / 'cdn/equipment' / e['image']
    if src.exists():
        shutil.copyfile(src, IMG_DIR / img)
    else:
        print('no image for', spec)
        img = None
    items[spec] = {
        'name': e['name'], 'version': e['version'], 'id': e['id'], 'slot': e['slot'],
        'img': img, 'speed': e.get('speed'), 'category': e.get('category'),
        'twoHanded': e['isTwoHanded'], 'off': e['offensive'], 'bon': e['bonuses'],
    }


for s in cfg['setups']:
    for spec in s['items'].values():
        add_item(spec)
    if 'dart' in s:
        add_item(s['dart'])

spell_out = {}
for sp in spells:
    if sp['spellbook'] == 'standard' and re.search(r' (Bolt|Blast|Wave|Surge)$', sp['name']) and sp['element']:
        # spell icons are not in the calc repo; they were fetched once from the wiki (img/items/<slug>.png)
        img = slug(sp['name']) + '.png'
        spell_out[sp['name']] = {'max': sp['max_hit'], 'element': sp['element'],
                                 'img': img if (IMG_DIR / img).exists() else None}

# Real bosses as presets. floor = defence floor from the wiki calc (DefenceReduction.ts); None = no floor.
PRESETS = [
    ('Araxxor', '', 90, 'Defence floor 90'),
    ('The Nightmare', '', 120, 'Defence floor 120'),
    ('Sol Heredit', '', None, 'No defence floor'),
    ('Nex', '', 250, 'Defence floor 250'),
    ('The Whisperer', 'Awakened', None, 'No defence floor'),
]
presets = []
for name, version, floor, note in PRESETS:
    m = next(x for x in monsters if x['name'] == name and x['version'] == version)
    d = m['defensive']
    dfn = m['skills']['def']
    if floor == 'nodrain':
        cap = 0
    elif floor is None:
        cap = 100
    else:
        cap = round(100 * (dfn - floor) / dfn) if dfn else 0
    weak = m.get('weakness') or {}
    presets.append({
        'name': name + (f' ({version})' if version else ''),
        'note': note + (f'; {weak["severity"]}% weak to {weak["element"]}' if weak else ''),
        'boss': {
            'def': dfn, 'magic': m['skills']['magic'], 'hp': m['skills']['hp'], 'size': m['size'],
            'stab': d['stab'], 'slash': d['slash'], 'crush': d['crush'], 'mdef': d['magic'],
            'light': d['light'], 'standard': d['standard'], 'heavy': d['heavy'],
            'severity': weak.get('severity', 0), 'defCap': cap, 'mdefCap': 100,
        },
    })

data = {'items': items, 'spells': spell_out, 'presets': presets}
js = '// Generated by tools/build_data.py from the OSRS wiki DPS calculator data. Do not edit.\n'
js += '// Setups are in data/setups.json.\n'
js += 'export const ITEMS = ' + json.dumps(data, indent=1) + ';\n'
(ROOT / 'js/items.js').write_text(js)
print(f'{len(items)} items, {len(spell_out)} spells, {len(presets)} presets')
